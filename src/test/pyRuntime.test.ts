suite('runtimeCallExpr', () => {
  const expr = runtimeCallExpr('datalog_emit', 'dict(a=1)', '/tmp/vscode-datalog/p/datalog_runtime.py');

  test('contains no braces, which logpoints would swallow', () => {
    notIncludes(expr, '{');
    notIncludes(expr, '}');
  });

  test('loads the module from the generated file', () => {
    includes(expr, "'/tmp/vscode-datalog/p/datalog_runtime.py'");
    includes(expr, 'exec(');
  });

  test('caches the namespace on builtins under a source-derived name', () => {
    includes(expr, RUNTIME_CACHE_ATTR);
    ok(/_datalog_rt_[0-9a-f]{8}/.test(RUNTIME_CACHE_ATTR), RUNTIME_CACHE_ATTR);
  });

  test('reuses the cached namespace instead of re-executing', () => {
    includes(expr, `getattr(_b, '${RUNTIME_CACHE_ATTR}', None) or `);
  });

  test('calls the requested entry point with the payload', () => {
    includes(expr, "['datalog_emit'](dict(a=1))");
  });
});

